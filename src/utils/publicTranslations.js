const PATTERNS = [
  [/^Bàn\s+(\d+)$/i, 'Table $1'],
  [/^(\d+)\s+người$/i, '$1 guests'],
  [/^(\d+)\s+phút$/i, '$1 minutes'],
  [/^(\d+)\s+món$/i, '$1 items'],
  [/^(\d+)\s+suất món$/i, '$1 items'],
  [/^(\d+)\s+dòng món$/i, '$1 items'],
  [/^Mã đặt bàn:\s*(.+)$/i, 'Reservation code: $1'],
  [/^Ghi chú:\s*(.+)$/i, 'Note: $1'],
  [/^Lý do:\s*(.+)$/i, 'Reason: $1'],
  [/^Mở cửa\s+(.+)$/i, 'Open $1'],
  [/^Dựa trên\s+(\d+)\s+lượt đánh giá$/i, 'Based on $1 reviews'],
  [/^Đã thêm\s+(.+)\s+vào giỏ hàng\.?$/i, 'Added $1 to cart.'],
  [/^Đã gửi đơn\s+#?(\d+)$/i, 'Order #$1 sent'],
  [/^Đã thêm món vào đơn\s+#?(\d+)$/i, 'Items added to order #$1'],
  [/^Đơn hiện tại\s+#?(\d+)$/i, 'Current order #$1'],
  [/^Các món mới sẽ được thêm vào đơn\s+#?(\d+)\.$/i, 'New items will be added to order #$1.'],
  [/^Đã áp dụng mã\s+(.+)\.$/i, 'Code $1 applied.'],
  [/^Đến\s+(.+)$/i, 'Until $1'],
  [/^Giảm\s+(.+)$/i, 'Save $1'],
  [/^Đơn hàng\s+#(.+)$/i, 'Order #$1'],
  [/^(.+)\s+trên 5 sao$/i, '$1 out of 5 stars'],
];

function preserveOuterWhitespace(original, translated) {
  const leading = original.match(/^\s*/)?.[0] || '';
  const trailing = original.match(/\s*$/)?.[0] || '';
  return `${leading}${translated}${trailing}`;
}

export function translatePublicText(value, language = 'en') {
  const original = String(value ?? '');
  if (language !== 'en' || !original.trim()) return original;
  const trimmed = original.trim();
  const normalized = trimmed.replace(/\s+/g, ' ');
  const exact = EN_TEXT[normalized] ?? EN_TEXT[trimmed];
  if (exact) return preserveOuterWhitespace(original, exact);

  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(normalized)) {
      pattern.lastIndex = 0;
      return preserveOuterWhitespace(original, normalized.replace(pattern, replacement));
    }
  }
  return original;
}
